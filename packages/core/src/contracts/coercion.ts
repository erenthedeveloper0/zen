/**
 * One conversion, chosen at boot from the schema's declared type.
 *
 * A closed set of five, on purpose. The temptation in a subsystem like this is
 * an extensible converter registry; the reason there isn't one is that every
 * entry here has to be something the *schema language* can ask for, and a
 * user-defined coercion has no way to be requested — the schema would have to
 * declare a type JSON Schema does not have. A schema that needs a bespoke
 * conversion already has the tool for it: `z.transform`, which runs inside the
 * validator where its failure has somewhere to go.
 */
export type CoerceOp =
  /** Strict decimal grammar → `number`; anything else passes through. */
  | { readonly kind: 'number' }
  /** As `number`, but refuses to silently lose precision — see `coerceInteger`. */
  | { readonly kind: 'integer' }
  | { readonly kind: 'boolean'; readonly words: BooleanWords }
  | {
      readonly kind: 'array'
      /** `?a=1` where an array is declared → `['1']`. */
      readonly wrap: boolean
      /** Split a single string on this separator first (`comma` style). */
      readonly split: string | null
      /** Applied to every element, or `null` when the element type is a string. */
      readonly items: CoerceOp | null
    }

export interface CoerceField {
  readonly key: string
  /**
   * The alternate key this field also collects, for `bracket` style: a field
   * named `tags` reads `tags[]` when `tags` is absent.
   */
  readonly altKey: string | null
  /** `''` → absent, applied before `op`. Separate so `op` can stay a pure map. */
  readonly emptyToUndefined: boolean
  readonly op: CoerceOp | null
}

/**
 * One source's plan. Never empty — an empty plan is `null`, so that "this route
 * coerces nothing" is representable only one way and the zero-cost check is a
 * null test rather than a length test.
 */
export interface CoercePlan {
  readonly source: ValidationSource
  readonly fields: readonly CoerceField[]
}

/**
 * What the route record carries, and what `explainRoute`, the OpenAPI generator
 * and the pipeline compiler all read — §2.4.
 *
 * On the record rather than inside the compiler for the same reason `hooks` and
 * `timeout` are: it is a function of static registration, so putting it in one
 * place is what stops the document, the explanation and the running code from
 * disagreeing about whether `?tags=a` is one string or a one-element array.
 */
export type CoercionRecord = ReadonlyMap<ValidationSource, CoercePlan>
