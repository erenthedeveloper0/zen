export type SyncClass = 'sync' | 'async' | 'maybe'

export interface PipelineStep {
  readonly kind: 'phase' | 'around' | 'after'
  readonly name: string
  readonly fn: Function
}

export interface PipelineSpec {
  readonly routeId: string
  readonly steps: readonly PipelineStep[]
  readonly handler: Function
  /** Emitted only when the route declares a body — §4.2 stage 6. */
  readonly intake: ((ctx: unknown) => Promise<void>) | null
  /** One entry per declared source, in the fixed order of §4.2 stage 7. */
  readonly validators: readonly ValidatorStep[]
  /**
   * Status → compiled serializer, for the statuses the route declares. The
   * status is a runtime value, so this stays a table rather than one function.
   */
  readonly serialize: SerializerTable | null
  /**
   * The negotiation step, on routes that declare more than one representation —
   * §13.4. `null` on every other route, which is what the zero-cost gate checks.
   *
   * A function rather than the plan, for the same reason `intake` is a function
   * rather than a body-parser registry: what the pipeline needs to emit is one
   * call, and everything about *how* the choice is made was decided at boot.
   *
   * Its presence also changes how the epilogue binds the response contract —
   * `attachNegotiated` instead of `attachSerializer` — so this field is read
   * twice by the generator and never at request time.
   */
  readonly negotiate?: ((ctx: unknown) => void) | null | undefined
  /**
   * The route's resolved hooks, per phase (§9). Absent means "none anywhere",
   * which is the same thing as every list being empty: no code is emitted.
   *
   * `onParse` is present in the plan but not read here — it composes into
   * `intake`, because a parse hook on a route that declares no body has no
   * stage to run in and must not resurrect one (§9.2).
   */
  readonly hooks?: HookPlan | undefined
  /**
   * Whether this route carries a deadline (§4.4).
   *
   * A boolean, not a duration: *how long* is the dispatcher's business, because
   * the budget can be shortened per request by an inbound header and the
   * pipeline is compiled once. All the pipeline needs to know is whether to
   * emit the stage marks and the abort checks at all — and on a route with no
   * deadline it emits neither, which is the same zero-cost rule the hook system
   * follows (§9.4) and is asserted the same way, against the generated bytes.
   */
  readonly deadline?: boolean | undefined
}

export interface ValidatorStep {
  readonly source: string
  readonly run: (ctx: unknown) => void | Promise<void>
}

