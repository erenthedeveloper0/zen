/**
 * Content negotiation — rfcs/0001 §13.4.
 *
 * The suite is organised around the four promises the design makes, because
 * every one of them can be broken silently:
 *
 *   1. **A route that declares one representation is not negotiated**, reads no
 *      `Accept`, stages no `Vary`, and emits no code. Checked against the
 *      generated bytes, for the reason §9.4 gives: a timing result inside the
 *      noise is also what a real small cost looks like.
 *   2. **The most specific matching range decides**, so `text/csv;q=0` plus a
 *      wildcard means "anything but CSV". This is the case implementations get
 *      backwards, and getting it backwards serves a representation the client
 *      explicitly refused.
 *   3. **`Vary: Accept` is on every response**, including the 406 and including
 *      a request that sent no `Accept` at all — the cache-correctness case
 *      §32.2 records for `Vary: Origin`.
 *   4. **A status that is not negotiated keeps its own Content-Type.** A 404
 *      problem document does not become `text/csv` because the client asked for
 *      CSV on the 200.
 */

const CSV = 'text/csv'
const JSON_MEDIA = 'application/json'

const Rows = jsonSchema<Array<{ id: number; email: string }>>({
  type: 'array',
  items: {
    type: 'object',
    properties: { id: { type: 'integer' }, email: { type: 'string' } },
    required: ['id', 'email'],
  },
})

const Problem = jsonSchema<{ code: string }>({
  type: 'object',
  properties: { code: { type: 'string' } },
  required: ['code'],
})

/** A CSV encoder that resolves its columns at boot — the shape §13.4 asks for. */
function csvEncoder(): void {
  registerMediaEncoder(CSV, (schema) => {
    const items = schema?.['items'] as Record<string, unknown> | undefined
    const columns = Object.keys((items?.['properties'] ?? {}) as Record<string, unknown>)
    return (value) => {
      const rows = (Array.isArray(value) ? value : [value]) as Array<Record<string, unknown>>
      return [columns.join(','), ...rows.map((r) => columns.map((c) => String(r[c] ?? '')).join(','))].join('\n')
    }
  })
}

