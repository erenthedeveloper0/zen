function negotiatedApp() {
  const app = makeApp()
  app.get('/rows', {
    response: { 200: { 'application/json': Rows, 'text/csv': Rows } },
  }, () => [{ id: 1, email: 'a@b.c', password: 'leaked' }] as never)
  return app
}

const get = (app: ReturnType<typeof makeApp>, path: string, accept?: string) =>
  app.inject('GET', path, accept === undefined ? {} : { headers: { accept } })

describe('end to end (§13.4)', () => {
  test('the chosen representation decides the writer and the Content-Type', async () => {
    const app = negotiatedApp()
    await app.ready()

    const json = await get(app, '/rows', JSON_MEDIA)
    assert.equal(json.header('content-type'), 'application/json; charset=utf-8')
    assert.deepEqual(json.json(), [{ id: 1, email: 'a@b.c' }])

    const csv = await get(app, '/rows', CSV)
    assert.equal(csv.header('content-type'), 'text/csv; charset=utf-8')
    assert.equal(csv.text(), 'id,email\n1,a@b.c')
  })

  /**
   * §13.3's guarantee has to survive the new dimension. It would be an easy
   * thing to lose: the negotiated path builds its serializers through a
   * different call site, and a path that forgot to compile one would fall back
   * to `JSON.stringify` and emit everything.
   */
  test('an undeclared field cannot be emitted, in either representation', async () => {
    const app = negotiatedApp()
    await app.ready()
    assert.equal((await get(app, '/rows', JSON_MEDIA)).text().includes('leaked'), false)
    assert.equal((await get(app, '/rows', CSV)).text().includes('leaked'), false)
  })

  test('no Accept header is the server preference, and it is the first declared', async () => {
    const app = negotiatedApp()
    await app.ready()
    assert.equal((await get(app, '/rows')).header('content-type'), 'application/json; charset=utf-8')
  })

  test('ctx.negotiated is set before the handler and carries the bare media type', async () => {
    const seen: Array<string | null> = []
    const app = makeApp()
    app.get('/rows', {
      response: { 200: { 'application/json': Rows, 'text/csv': Rows } },
    }, (ctx) => { seen.push(ctx.negotiated); return [] as never })
    app.get('/plain', { response: { 200: Rows } }, (ctx) => { seen.push(ctx.negotiated); return [] as never })
    await app.ready()

    await get(app, '/rows', CSV)
    await get(app, '/plain', CSV)
    assert.deepEqual(seen, ['text/csv', null], 'null means "this route has nothing to decide"')
  })

  test('an unacceptable Accept is a 406 that lists what the route can produce', async () => {
    const app = negotiatedApp()
    await app.ready()

    const res = await get(app, '/rows', 'application/xml')
    assert.equal(res.status, 406)
    const problem = res.json<{ code: string; errors: { available: string[] } }>()
    assert.equal(problem.code, Codes.NOT_ACCEPTABLE)
    assert.deepEqual(problem.errors.available, [JSON_MEDIA, CSV])
  })

  test('the 406 is an ordinary HttpError, so onError sees it', async () => {
    const seen: string[] = []
    const app = negotiatedApp()
    app.hook('onError', (_ctx, error) => { seen.push((error as { code: string }).code) })
    await app.ready()

    await get(app, '/rows', 'application/xml')
    assert.deepEqual(seen, [Codes.NOT_ACCEPTABLE])
    assert.ok(new NotAcceptable() instanceof Error)
  })

  /**
   * The `Vary: Origin` lesson (§32.2), transposed. A response with no `Vary` is
   * one a shared cache may hand to a client that asked for something else, and
   * the two requests that most need the header are the two a naive
   * implementation skips: the one that sent no `Accept`, and the one that was
   * refused.
   */
  test('Vary: Accept is present with no Accept header, and on the 406', async () => {
    const app = negotiatedApp()
    await app.ready()

    assert.equal((await get(app, '/rows')).header('vary'), 'Accept', 'no Accept header')
    assert.equal((await get(app, '/rows', CSV)).header('vary'), 'Accept')
    assert.equal((await get(app, '/rows', 'application/xml')).header('vary'), 'Accept', 'on the 406')
  })

  test('a route that is not negotiated stages no Vary and ignores Accept', async () => {
    const app = makeApp()
    app.get('/plain', { response: { 200: Rows } }, () => [{ id: 1, email: 'a@b.c' }] as never)
    await app.ready()

    const res = await get(app, '/plain', CSV)
    assert.equal(res.status, 200, 'RFC 9110 permits disregarding Accept')
    assert.equal(res.header('vary'), undefined)
    assert.equal(res.header('content-type'), 'application/json; charset=utf-8')
  })

  /**
   * §12.1's "one envelope", from the other side. A status declared in the plain
   * form is not subject to negotiation, and inheriting the negotiated
   * Content-Type would put `text/csv` on a JSON problem document — a failure
   * that looks like a client bug and is not.
   */
  test('a status declared in the plain form keeps its own Content-Type', async () => {
    const app = makeApp()
    app.get('/rows', {
      response: {
        200: { 'application/json': Rows, 'text/csv': Rows },
        404: Problem,
      },
    }, (ctx) => ctx.json({ code: 'GONE', extra: 'dropped' }, { status: 404 }) as never)
    await app.ready()

    const res = await get(app, '/rows', CSV)
    assert.equal(res.status, 404)
    assert.equal(res.header('content-type'), 'application/json; charset=utf-8', 'not text/csv')
    assert.deepEqual(res.json(), { code: 'GONE' }, 'and its own contract still filtered')
  })

  test('a staged status picks the contract egress will actually send', async () => {
    const app = makeApp()
    app.get('/rows', {
      response: {
        200: { 'application/json': Rows, 'text/csv': Rows },
        201: { 'application/json': Rows, 'text/csv': Rows },
      },
    }, (ctx) => { ctx.res.status(201); return [{ id: 7, email: 'z@z.z' }] as never })
    await app.ready()

    const res = await get(app, '/rows', CSV)
    assert.equal(res.status, 201)
    assert.equal(res.text(), 'id,email\n7,z@z.z')
  })

  test('an explicit reply media wins — the handler is the authority it declared', async () => {
    const app = makeApp()
    app.get('/rows', {
      response: { 200: { 'application/json': Rows, 'text/csv': Rows } },
    }, (ctx) => ctx.text('raw', { media: 'text/plain; charset=utf-8' }) as never)
    await app.ready()

    const res = await get(app, '/rows', CSV)
    assert.equal(res.header('content-type'), 'text/plain; charset=utf-8')
  })

  test('HEAD negotiates and keeps the headers, with no body (RFC 9110 §9.3.2)', async () => {
    const app = negotiatedApp()
    await app.ready()

    const res = await app.inject('HEAD', '/rows', { headers: { accept: CSV } })
    assert.equal(res.status, 200)
    assert.equal(res.header('content-type'), 'text/csv; charset=utf-8')
    assert.equal(res.header('vary'), 'Accept')
    assert.equal(res.text(), '')
  })

  test('an onSerialize hook that swaps the payload keeps the representation', async () => {
    const app = negotiatedApp()
    app.hook('onSerialize', (_ctx, payload) => (payload as unknown[]).concat([{ id: 2, email: 'c@d.e' }]))
    await app.ready()

    const res = await get(app, '/rows', CSV)
    assert.equal(res.header('content-type'), 'text/csv; charset=utf-8')
    assert.equal(res.text(), 'id,email\n1,a@b.c\n2,c@d.e')
  })

  /**
   * The test above does *not* cover `replacePayload`'s handling of `media`, and
   * finding that out is what the negative-control script is for. The epilogue
   * runs `onSerialize` *before* the response contract is bound (§13.3.5), so at
   * the moment a hook swaps the payload there is no negotiated media on the
   * body yet — the assertion passed with the preservation deleted.
   *
   * It is still reachable, and through a documented surface: an `around`
   * middleware receives the Reply from `next()`, which has been through the
   * epilogue and *is* bound, and `replacePayload` is public API. So the
   * behaviour is right and the test was aimed at the wrong path. Here it is
   * aimed at the right one.
   */
  test('replacePayload keeps the negotiated media on an already-bound reply', () => {
    const bound = jsonReply([{ id: 1 }])
    ;(bound as { body: unknown }).body = {
      kind: 'json',
      value: [{ id: 1 }],
      serialize: () => 'id\n1',
      media: 'text/csv; charset=utf-8',
    }

    const swapped = replacePayload(bound, [{ id: 2 }])
    const body = swapped.body as { media?: string; serialize?: unknown }
    assert.equal(body.media, 'text/csv; charset=utf-8', 'the representation survived the swap')
    assert.notEqual(body.serialize, undefined, 'and so did the contract')
    assert.equal(encodeBody(swapped).media, 'text/csv; charset=utf-8')
  })

  test('negotiation runs before intake, so a refused request never reads a body', async () => {
    let parsed = 0
    const app = makeApp()
    app.post('/rows', {
      // A real validator: `jsonSchema()` describes without validating and
      // `ready()` refuses it on a request source (§13.3.6).
      body: shaped({ type: 'object', properties: { n: { type: 'number' } } }),
      response: { 200: { 'application/json': Rows, 'text/csv': Rows } },
    }, () => [] as never)
    app.hook('onParse', () => { parsed++ })
    await app.ready()

    const res = await app.inject('POST', '/rows', {
      headers: { accept: 'application/xml', 'content-type': JSON_MEDIA },
      body: { n: 1 },
    })
    assert.equal(res.status, 406)
    assert.equal(parsed, 0, 'the body of a request we were going to refuse was never read')
  })
})

describe('boot diagnostics (§13.4, §12.7)', () => {
  test('a media type with a parameter is refused, naming the bare type', async () => {
    const app = makeApp()
    app.get('/x', { response: { 200: { 'text/csv; charset=utf-8': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      assert.match(error.message, /ZEN_MEDIA_TYPE_INVALID/)
      assert.match(error.message, /"text\/csv"/, 'the fix names the type to write instead')
      return true
    })
  })

  test('a wildcard offer is refused', async () => {
    const app = makeApp()
    app.get('/x', { response: { 200: { '*/*': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), /ZEN_MEDIA_TYPE_INVALID/)
  })

  test('the same media type twice is refused, because only one could be reached', async () => {
    const app = makeApp()
    app.get('/x', { response: { 200: { 'application/json': Rows, 'Application/JSON': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), /ZEN_MEDIA_TYPE_INVALID/)
  })

  test('a media type with no encoder is refused, naming registerMediaEncoder', async () => {
    __resetMediaEncoders()
    const app = makeApp()
    app.get('/x', { response: { 200: { 'application/json': Rows, 'text/csv': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      assert.match(error.message, /ZEN_MEDIA_TYPE_UNSUPPORTED/)
      assert.match(error.message, /registerMediaEncoder\('text\/csv'/)
      return true
    })
  })

  test('two statuses offering different media types is refused, naming both', async () => {
    const app = makeApp()
    app.get('/x', {
      response: {
        200: { 'application/json': Rows, 'text/csv': Rows },
        201: { 'application/json': Rows },
      },
    }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      assert.match(error.message, /ZEN_NEGOTIATION_INCONSISTENT/)
      assert.match(error.message, /200/)
      assert.match(error.message, /201/)
      return true
    })
  })

  test('two statuses in a different order is refused too — order is the preference', async () => {
    const app = makeApp()
    app.get('/x', {
      response: {
        200: { 'application/json': Rows, 'text/csv': Rows },
        201: { 'text/csv': Rows, 'application/json': Rows },
      },
    }, () => [] as never)
    await assert.rejects(app.ready(), /ZEN_NEGOTIATION_INCONSISTENT/)
  })

  test('an encoder that refuses a schema at boot is a diagnostic, not a crash', async () => {
    __resetMediaEncoders()
    registerMediaEncoder(CSV, () => { throw new Error('rows only') })
    const app = makeApp()
    app.get('/x', { response: { 200: { 'application/json': Rows, 'text/csv': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      assert.match(error.message, /ZEN_MEDIA_TYPE_UNSUPPORTED/)
      assert.match(error.message, /rows only/, "the encoder's own message survives")
      return true
    })
  })

  test('a typo alongside real media types names the typo, not the schema', async () => {
    const app = makeApp()
    app.get('/x', { response: { 200: { 'application/json': Rows, csv: Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      assert.match(error.message, /ZEN_MEDIA_TYPE_INVALID/)
      assert.match(error.message, /"csv", which is not a media type/)
      assert.match(error.message, /type\/subtype/, 'the fix shows the shape to write')
      return true
    })
  })

  test('the diagnostics aggregate — three bad routes is one boot, not three', async () => {
    const app = makeApp()
    app.get('/a', { response: { 200: { 'application/json': Rows, nope: Rows } } }, () => [] as never)
    app.get('/b', { response: { 200: { 'also/*': Rows } } }, () => [] as never)
    app.get('/c', { response: { 200: { 'text/csv; q=1': Rows } } }, () => [] as never)
    await assert.rejects(app.ready(), (error: Error) => {
      for (const path of ['/a', '/b', '/c']) {
        assert.match(error.message, new RegExp(path), `${path} was not reported in the same run`)
      }
      return true
    })
  })

  test('a route with one media type in the variant form is legal, and is negotiated', async () => {
    const app = makeApp()
    app.get('/strict', { response: { 200: { 'application/json': Rows } } }, () => [] as never)
    await app.ready()

    assert.equal((await get(app, '/strict', CSV)).status, 406, 'the variant form is the opt-in to strictness')
    assert.equal((await get(app, '/strict', JSON_MEDIA)).status, 200)
    assert.equal((await get(app, '/strict')).header('vary'), 'Accept')
  })
})

