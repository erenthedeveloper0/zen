describe('Accept parsing (§13.4)', () => {
  test('an absent, empty or unparseable header is the same thing: nothing', () => {
    assert.equal(parseAccept(undefined), null)
    assert.equal(parseAccept(''), null)
    assert.equal(parseAccept('   '), null)
    assert.equal(parseAccept('garbage'), null, 'no slash, so no range')
    assert.equal(parseAccept(',,,'), null)
  })

  test('a malformed range is skipped, and the readable ones still count', () => {
    const ranges = parseAccept('text/csv, garbage, application/json;q=0.5')
    assert.notEqual(ranges, null)
    assert.equal(ranges!.length, 2)
    assert.deepEqual(ranges!.map((r) => `${r.type}/${r.sub}@${r.q}`), ['text/csv@1', 'application/json@0.5'])
  })

  test('quality defaults to 1, clamps to [0,1], and survives a typo', () => {
    const q = (header: string): number => (parseAccept(header) as ReadonlyArray<{ q: number }>)[0]!.q
    assert.equal(q('text/csv'), 1)
    assert.equal(q('text/csv;q=0.25'), 0.25)
    assert.equal(q('text/csv;q=0'), 0)
    assert.equal(q('text/csv;q=9'), 1, 'clamped')
    assert.equal(q('text/csv;q=-3'), 0, 'clamped')
    assert.equal(q('text/csv;q=banana'), 1, 'a typo means "I want this", not "I refuse it"')
    assert.equal(q('text/csv;Q=0.5'), 0.5, 'parameter names are case-insensitive')
  })

  test('specificity is recorded, and it is what RFC 9110 orders by', () => {
    const ranges = parseAccept('*/*, text/*, text/csv') as ReadonlyArray<{ specificity: number }>
    assert.deepEqual(ranges.map((r) => r.specificity), [0, 1, 2])
  })

  test('a wildcard type with a concrete subtype is not a range', () => {
    assert.equal(parseAccept('*/json'), null)
  })

  test('a comma inside a quoted parameter does not split the range', () => {
    const ranges = parseAccept('text/csv;label="a,b"') as ReadonlyArray<unknown>
    assert.equal(ranges.length, 1, 'one range, not two malformed ones')
  })

  test('ranges past the cap are ignored, and the cap is small enough to bound the work', () => {
    const many = new Array(200).fill('text/plain').join(', ')
    assert.equal((parseAccept(many) as ReadonlyArray<unknown>).length, MAX_ACCEPT_RANGES)
    assert.ok(MAX_ACCEPT_RANGES >= 8, 'a browser sends up to five; the cap must not clip a real client')
  })

  test('parameters other than q are ignored — the stated limitation', () => {
    const ranges = parseAccept('application/json;profile="urn:x";q=0.5') as ReadonlyArray<{ q: number }>
    assert.equal(ranges[0]!.q, 0.5)
    assert.equal(qualityFor(ranges as never, 'application', 'json'), 0.5)
  })
})

describe('the match (§13.4)', () => {
  const offers = offersOf([JSON_MEDIA, CSV])
  const pick = (accept: string): string | null => {
    const index = selectOffer(accept, offers)
    return index === -1 ? null : (offers[index]!.media)
  }

  test('an exact type wins', () => {
    assert.equal(pick('text/csv'), CSV)
    assert.equal(pick('application/json'), JSON_MEDIA)
  })

  test('a subtype wildcard matches within its type', () => {
    assert.equal(pick('text/*'), CSV)
    assert.equal(pick('application/*'), JSON_MEDIA)
  })

  test('a full wildcard takes the server preference — declaration order', () => {
    assert.equal(pick('*/*'), JSON_MEDIA)
    assert.equal(
      offersOf([CSV, JSON_MEDIA])[selectOffer('*/*', offersOf([CSV, JSON_MEDIA]))]!.media,
      CSV,
      'reverse the declaration and the answer reverses with it',
    )
  })

  test('quality decides between two things the client will accept', () => {
    assert.equal(pick('application/json;q=0.8, text/csv;q=0.9'), CSV)
    assert.equal(pick('application/json;q=0.9, text/csv;q=0.8'), JSON_MEDIA)
  })

  test('a tie goes to the server, not to the alphabet', () => {
    assert.equal(pick('text/csv;q=0.5, application/json;q=0.5'), JSON_MEDIA)
  })

  test('nothing acceptable is -1, and that is the 406', () => {
    assert.equal(pick('application/xml'), null)
    assert.equal(pick('image/png, application/pdf'), null)
  })

  /**
   * The case every implementation that scores by "highest q among matching
   * ranges" gets backwards — and getting it backwards means serving a
   * representation the client named and refused.
   */
  test('an explicit q=0 is honoured even under a wildcard that allows everything', () => {
    assert.equal(pick('text/csv;q=0, */*'), JSON_MEDIA, 'anything except CSV')
    assert.equal(pick('application/json;q=0, */*'), CSV)
  })

  test('q=0 on everything is a 406, not a fallback', () => {
    assert.equal(pick('*/*;q=0'), null)
    assert.equal(pick('text/csv;q=0, application/json;q=0'), null)
  })

  test('a more specific range overrides a less specific one in both directions', () => {
    assert.equal(pick('text/*;q=0, */*'), JSON_MEDIA, 'no text at all')
    assert.equal(pick('*/*;q=0, text/csv'), CSV, 'nothing, except CSV')
  })
})

describe('the cache is a cache, not a correctness surface (§13.4)', () => {
  const reps = new Map<string, Representation>([
    [JSON_MEDIA, { media: JSON_MEDIA, contentType: 'application/json; charset=utf-8', statuses: new Set([200]), writers: new Map() }],
    [CSV, { media: CSV, contentType: 'text/csv; charset=utf-8', statuses: new Set([200]), writers: new Map() }],
  ])

  test('a warm answer equals a cold one, including a cached 406', () => {
    const cold = makeNegotiator([JSON_MEDIA, CSV], reps)
    const warm = makeNegotiator([JSON_MEDIA, CSV], reps)
    for (const header of ['text/*', 'application/xml', 'text/csv;q=0, */*', '*/*;q=0']) {
      const first = cold(header)
      const second = cold(header)
      assert.equal(first, second, `${header} changed on the second call`)
      assert.equal(warm(header), first, 'a fresh negotiator agrees with a warmed one')
    }
  })

  test('eviction never changes an answer', () => {
    const negotiate = makeNegotiator([JSON_MEDIA, CSV], reps)
    const before = negotiate('text/*;q=0.4')
    for (let i = 0; i < NEGOTIATION_CACHE_LIMIT * 3; i++) negotiate(`application/x-${i};q=0.1, text/*;q=0.9`)
    assert.equal(negotiate('text/*;q=0.4'), before, 'the entry was evicted, not corrupted')
  })

  test('the cache is bounded by attacker-chosen keys', () => {
    const negotiate = makeNegotiator([JSON_MEDIA, CSV], reps)
    for (let i = 0; i < 5_000; i++) negotiate(`application/x-${i}`)
    // No accessor to the map by design; the bound is asserted through the
    // constant the implementation is required to honour, and through the
    // eviction test above proving a full map still answers correctly.
    assert.ok(NEGOTIATION_CACHE_LIMIT <= 64, 'a cache keyed on a header must stay small')
  })
})

describe('media type declarations (§13.4)', () => {
  test('a bare type/subtype is accepted and lowercased', () => {
    const parsed = normaliseMediaType('Application/JSON')
    assert.ok(!isMediaProblem(parsed))
    assert.equal((parsed as { media: string }).media, JSON_MEDIA)
  })

  test('a parameter, a wildcard and a non-media-type are each refused, distinctly', () => {
    assert.equal(normaliseMediaType('text/csv; charset=utf-8'), 'has-parameters')
    assert.equal(normaliseMediaType('*/*'), 'wildcard')
    assert.equal(normaliseMediaType('text/*'), 'wildcard')
    assert.equal(normaliseMediaType('json'), 'not-a-media-type')
    assert.equal(normaliseMediaType(''), 'not-a-media-type')
  })

  test('the JSON family is the compiled serializer, and +json is in it', () => {
    assert.equal(isJsonMedia('application/json'), true)
    assert.equal(isJsonMedia('application/vnd.acme.v2+json'), true)
    assert.equal(isJsonMedia('application/problem+json'), true)
    assert.equal(isJsonMedia('text/csv'), false)
  })

  test('the charset is appended, because a Serializer returns a string', () => {
    assert.equal(wireMediaType('text/csv'), 'text/csv; charset=utf-8')
    assert.equal(wireMediaType(JSON_MEDIA), 'application/json; charset=utf-8')
  })

  test('a variant record is told from a schema by its keys, and {} is not one', () => {
    assert.equal(isVariantRecord({ 'application/json': Rows }), true)
    assert.equal(isVariantRecord({ type: 'object', properties: {} }), false)
    assert.equal(isVariantRecord({ $ref: '#/$defs/User' }), false, "a $ref's value has slashes; its key does not")
    assert.equal(isVariantRecord(Rows), false, 'jsonSchema() is a schema')
    assert.equal(isVariantRecord({}), false, 'a typo, not a declaration of nothing')
    assert.equal(isVariantRecord({ nope: Rows }), false, 'no slash anywhere — indistinguishable from a bad schema')
    assert.equal(isVariantRecord([]), false)
    assert.equal(isVariantRecord(null), false)
  })

  /**
   * The case that argued `every` down to `any`. One typo'd key among real media
   * types is a variant record with a bad key, and saying so is the whole
   * difference between a usable diagnostic and "your schema would not convert".
   */
  test('one typo among real media types is still a variant record', () => {
    assert.equal(isVariantRecord({ 'application/json': Rows, csv: Rows }), true)
  })
})

