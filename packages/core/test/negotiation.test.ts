describe('zero cost when it is not used (§9.4)', () => {
  /**
   * The pipeline unit for one route, and *only* the pipeline unit.
   *
   * `find(u => u.name.includes('/plain'))` is what the first draft of this
   * suite used, and it was wrong in the way §20.7 warns about: response
   * serializers are compiled before pipelines and are named
   * `GET /plain#200`, so the search matched a serializer and every assertion
   * below passed without ever looking at a pipeline. The count assertion in the
   * last test is what caught it — it expected one `d.negotiate(ctx)` and found
   * zero in a unit that could not have contained one.
   */
  const pipelineOf = (app: ReturnType<typeof makeApp>, method: string, path: string): string => {
    const unit = app.generatedSource().find((u) => u.name === `pipeline:${method}_${path}`)
    assert.ok(unit !== undefined, `no pipeline unit for ${method} ${path}`)
    return unit.source
  }

  /**
   * The house gate, against the generated bytes rather than a clock. A route
   * that declares one representation must compile to exactly what it compiled
   * before this feature existed — no `Accept` read, no `Vary`, no branch.
   */
  test('a plain route emits a pipeline byte-identical to one in an app with no negotiation', async () => {
    const source = async (declare: boolean): Promise<string> => {
      const app = makeApp()
      app.get('/plain', { response: { 200: Rows } }, () => [] as never)
      if (declare) {
        app.get('/rows', { response: { 200: { 'application/json': Rows, 'text/csv': Rows } } }, () => [] as never)
      }
      await app.ready()
      return pipelineOf(app, 'GET', '/plain')
    }

    assert.equal(await source(false), await source(true))
  })

  test('and its emitted text mentions neither negotiation nor the negotiated binding', async () => {
    const app = makeApp()
    app.get('/plain', { response: { 200: Rows } }, () => [] as never)
    await app.ready()

    const emitted = pipelineOf(app, 'GET', '/plain')
    assert.equal(emitted.includes('negotiate'), false)
    assert.equal(emitted.includes('attachNegotiated'), false)
    assert.match(emitted, /attachSerializer/, 'it still binds the plain contract')
  })

  test('a route with no response schema at all is untouched too', async () => {
    const app = makeApp()
    app.get('/bare', () => ({ ok: true }))
    await app.ready()

    const emitted = pipelineOf(app, 'GET', '/bare')
    assert.equal(emitted.includes('negotiate'), false)
    assert.equal(emitted.includes('Serializer'), false)
  })

  test('a negotiated route emits exactly one negotiation call', async () => {
    const app = negotiatedApp()
    await app.ready()

    const emitted = pipelineOf(app, 'GET', '/rows')
    assert.equal(emitted.split('d.negotiate(ctx)').length - 1, 1)
    assert.match(emitted, /attachNegotiated/)
    assert.equal(emitted.includes('attachSerializer'), false, 'one binding, not both')
  })
})
