import { test, describe, beforeEach } from 'node:test'
import assert from 'node:assert/strict'
import {
  buildCoercePlan, resolveCoercion, planRoute, isInert, compileCoercer, walkCoercer,
  generateCoercerSource, coerceNumber, coerceInteger, coerceBoolean, splitList,
  explainRoute, markSync, CodeGen, DEFAULT_CAPABILITIES, COERCION_DEFAULTS, COERCION_OFF,
  jsonSchema,
  type CoercePlan, type CoercionProfile, type JsonSchema, type RouteRecord,
} from '@erenthedeveloper0/zen-core'
import { makeApp, shaped, silentLogger } from './helpers.ts'

/**
 * Coercion profiles — rfcs/0001 §11.4.
 *
 * The suite is organised around the three rules the design turns on, because
 * each one is a promise that can only be broken silently:
 *
 *   1. a position that accepts a string is never coerced;
 *   2. a value coercion will not convert passes through, and the *schema*
 *      reports it;
 *   3. a route with nothing to convert emits no coercion code at all.
 *
 * The third is checked against the generated bytes rather than a clock, for the
 * reason §9.4 gives: a timing result inside the noise is also what a real small
 * cost looks like.
 */

const codegen = new CodeGen({ caps: DEFAULT_CAPABILITIES })

const profile = (overrides: Partial<CoercionProfile> = {}): CoercionProfile => ({
  ...COERCION_DEFAULTS.query,
  ...overrides,
})

function planOf(json: JsonSchema, overrides: Partial<CoercionProfile> = {}): CoercePlan | null {
  const outcome = buildCoercePlan(shaped(json as Record<string, unknown>), 'query', profile(overrides))
  assert.equal(outcome.kind, 'ok', `expected a plan, got ${outcome.kind}`)
  return outcome.kind === 'ok' ? outcome.plan : null
}

/** Both engines, on the same plan and the same input. Every case runs both. */
function both(plan: CoercePlan, input: Record<string, unknown>): Record<string, unknown> {
  const compiled = compileCoercer(plan, 'test', codegen)
  const walked = walkCoercer(plan)

  const a = compiled({ ...input }) as Record<string, unknown>
  const b = walked({ ...input }) as Record<string, unknown>
  assert.deepEqual(a, b, `compiled and walked coercers diverged\n${generateCoercerSource(plan)}`)
  return a
}

function coerced(json: JsonSchema, input: Record<string, unknown>, overrides: Partial<CoercionProfile> = {}): Record<string, unknown> {
  const plan = planOf(json, overrides)
  return plan === null ? input : both(plan, input)
}

const objectOf = (properties: Record<string, JsonSchema>): JsonSchema => ({ type: 'object', properties })

