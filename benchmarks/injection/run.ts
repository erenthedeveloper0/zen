/**
 * What the injection defences cost, and three gates — rfcs/0001 §19.5, I9.
 *
 * `node benchmarks/injection/run.ts`
 *
 * §19.5 describes two defences that the security model claimed for two
 * releases before either existed: HTML escaped by construction (`html`,
 * `SafeHtml`, `ctx.html()`) and redirects that stay on the origin
 * (`ctx.redirect()`, `redirect.allowExternal`). Three of the sections below
 * fail the build, and all three are correctness gates living in a benchmark for
 * the reason §11.4's and §32.3's do: each guards a property a later
 * optimisation is tempted to trade away, because the unsafe version is always
 * the faster one.
 *
 *   1. **A hostile value never escapes its hole** — twelve payloads in seven
 *      positions, judged by the WHATWG URL parser and a grammar for escaped
 *      text, neither of which shares code with `runtime/html.ts`. **Gated.**
 *   2. **A hostile redirect never leaves the origin** — twenty spellings under
 *      three policies, judged by the WHATWG URL parser on both an http and an
 *      https page, which is what a browser will do with the `Location` header.
 *      **Gated.**
 *   3. **A redirect policy changes no generated byte.** The policy is data on
 *      the shared `ContextEnv`; if configuring it ever changed a pipeline or
 *      the context class, it would have become a per-request cost. **Gated.**
 *   4. **`escapeHtml`**, against the regex `replace` it replaced in
 *      `@erenthedeveloper0/zen-openapi` — the measurement that rewrote it.
 *   5. **`html```** against the same card written by hand with `escapeHtml`,
 *      and what the first render of a template (its analysis) costs.
 *   6. **`ctx.redirect()`** — a path, which is decided without a `URL`
 *      object; an allowlisted origin, which is parsed; a refusal.
 *   7. **What a JSON handler pays for `() => html```**: nothing, and the
 *      section keeps the measurement that made it nothing. Checking every
 *      returned object for `SafeHtml` cost +16% of `finalize`; a fragment is
 *      now an async iterable of its markup, so the check sits in the branch
 *      `finalize` already takes for streams, and a plain object never reaches it.
 */
import {
  createApp, finalize, html, escapeHtml, NEUTRAL_URL, redirectReply, compileRedirectPolicy,
  isReply, jsonReply, textReply, bytesReply, emptyReply, MutableReply, isSafeHtml, markSync,
  type Logger, type SafeHtml, type ZenApp,
} from '@erenthedeveloper0/zen-core'
import { ZenRouter, parsePath } from '@erenthedeveloper0/zen-router'

const pathParser = {
  parse: (path: string) => {
    const parsed = parsePath(path)
    return { path: parsed.path, segments: parsed.segments }
  },
}

const silent: Logger = (() => {
  const noop = () => {}
  const logger = { level: 'fatal' as const, child: () => logger, trace: noop, debug: noop, info: noop, warn: noop, error: noop, fatal: noop }
  return logger
})()

const REPS = 9

let failures = 0
function fail(message: string): void {
  failures++
  console.log(`    ✖ ${message}`)
}

/** Median ns per call of `fn`, best-effort isolated: warm, then REPS timed runs. */
function nsPerCall(fn: () => unknown, iterations: number): number {
  let sink = 0
  for (let i = 0; i < Math.min(iterations, 50_000); i++) sink ^= fn() === undefined ? 0 : 1
  const samples: number[] = []
  for (let rep = 0; rep < REPS; rep++) {
    const start = process.hrtime.bigint()
    for (let i = 0; i < iterations; i++) sink ^= fn() === undefined ? 0 : 1
    samples.push(Number(process.hrtime.bigint() - start) / iterations)
  }
  if (sink === 42) console.log('')
  samples.sort((a, b) => a - b)
  return samples[Math.floor(samples.length / 2)] as number
}

/**
 * Two arms inside every repetition, alternating which runs first — §9.9's
 * lesson: two separately timed functions tier independently, and the drift
 * between them exceeds the effects being claimed.
 */
function paired(a: () => unknown, b: () => unknown, iterations: number): { a: number; b: number; ratio: number; spread: number } {
  let sink = 0
  for (let i = 0; i < 50_000; i++) sink ^= (a() === undefined ? 0 : 1) ^ (b() === undefined ? 0 : 2)
  const aTimes: number[] = []
  const bTimes: number[] = []
  const ratios: number[] = []
  for (let rep = 0; rep < REPS; rep++) {
    const order = rep % 2 === 0 ? [a, b] : [b, a]
    const times: number[] = []
    for (const arm of order) {
      const start = process.hrtime.bigint()
      for (let i = 0; i < iterations; i++) sink ^= arm() === undefined ? 0 : 1
      times.push(Number(process.hrtime.bigint() - start) / iterations)
    }
    const [first, second] = times as [number, number]
    const ta = rep % 2 === 0 ? first : second
    const tb = rep % 2 === 0 ? second : first
    aTimes.push(ta)
    bTimes.push(tb)
    ratios.push(tb / ta)
  }
  if (sink === 42) console.log('')
  ratios.sort((x, y) => x - y)
  const ratio = ratios[Math.floor(ratios.length / 2)] as number
  return {
    a: Math.min(...aTimes),
    b: Math.min(...bTimes),
    ratio,
    spread: ((ratios[ratios.length - 1] as number) - (ratios[0] as number)) / ratio,
  }
}

const noise = (ratio: number, spread: number): string =>
  Math.abs(ratio - 1) <= spread ? 'INSIDE NOISE' : 'ABOVE NOISE'

/** The five entities `escapeHtml` writes, decoded — what a browser shows. */
const decode = (text: string): string =>
  text.replace(/&(amp|lt|gt|quot|#39);/g, (_, name: string) =>
    ({ amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" })[name] as string)

const ESCAPED = /^(?:[^&<>"']|&(?:amp|lt|gt|quot|#39);)*$/
const BASES = ['http://app.test/p/', 'https://app.test/p/'] as const

console.log('\n  Injection defences — rfcs/0001 §19.5')
console.log(`  node ${process.version}\n`)

// ── 1. a hostile value never escapes its hole ───────────────────────────────

console.log('  1. A hostile value never escapes its hole  (gate)\n')
{
  const PAYLOADS = [
    '<script>alert(1)</script>', '"><img src=x onerror=alert(1)>', "' onmouseover='alert(1)",
    'javascript:alert(1)', ' JaVa\tScRiPt:alert(1)', 'data:text/html,<script>alert(1)</script>',
    'vbscript:msgbox(1)', '//evil.example/x.js', '/\\evil.example/x.js', '&#106;avascript:alert(1)',
    '</title><script>alert(1)</script>', '--><script>alert(1)</script>',
  ]
  type Position = { name: string; render: (v: string) => SafeHtml; before: string; after: string; kind: 'text' | 'link' | 'code' }
  const POSITIONS: Position[] = [
    { name: 'element content', render: (v) => html`<p>${v}</p>`, before: '<p>', after: '</p>', kind: 'text' },
    { name: 'double-quoted attribute', render: (v) => html`<a title="${v}">x</a>`, before: '<a title="', after: '">x</a>', kind: 'text' },
    { name: 'single-quoted attribute', render: (v) => html`<a title='${v}'>x</a>`, before: "<a title='", after: "'>x</a>", kind: 'text' },
    { name: '<title>', render: (v) => html`<title>${v}</title>`, before: '<title>', after: '</title>', kind: 'text' },
    { name: '<textarea>', render: (v) => html`<textarea>${v}</textarea>`, before: '<textarea>', after: '</textarea>', kind: 'text' },
    { name: 'href', render: (v) => html`<a href="${v}">x</a>`, before: '<a href="', after: '">x</a>', kind: 'link' },
    { name: '<script src>', render: (v) => html`<script src="${v}"></script>`, before: '<script src="', after: '"></script>', kind: 'code' },
  ]

  for (const position of POSITIONS) {
    let held = 0
    for (const payload of PAYLOADS) {
      const out = String(position.render(payload))
      if (!out.startsWith(position.before) || !out.endsWith(position.after)) {
        fail(`${position.name}: ${JSON.stringify(payload)} changed the written text around the hole`)
        continue
      }
      const hole = out.slice(position.before.length, out.length - position.after.length)
      if (!ESCAPED.test(hole)) {
        fail(`${position.name}: ${JSON.stringify(payload)} wrote markup — ${JSON.stringify(hole)}`)
        continue
      }
      const value = decode(hole)
      if (position.kind !== 'text' && value !== NEUTRAL_URL) {
        for (const base of BASES) {
          let url: URL | null = null
          try { url = new URL(value, base) } catch { url = null }
          if (url === null) continue
          if (!['http:', 'https:', 'mailto:', 'tel:'].includes(url.protocol)) {
            fail(`${position.name}: ${JSON.stringify(payload)} kept the ${url.protocol} scheme`)
          }
          if (position.kind === 'code' && url.origin !== new URL(base).origin) {
            fail(`${position.name}: ${JSON.stringify(payload)} loads from ${url.origin}`)
          }
        }
      }
      held++
    }
    console.log(`    ${held === PAYLOADS.length ? '✔' : '✖'} ${position.name.padEnd(26)} ${held}/${PAYLOADS.length} payloads held`)
  }
  console.log('')
}

// ── 2. a hostile redirect never leaves the origin ───────────────────────────

console.log('  2. A hostile redirect never leaves the origin  (gate)\n')
{
  const TARGETS = [
    '/dashboard', '?next=1', '#top', 'relative', '//evil.example', '///evil.example', '/\\evil.example',
    '\\\\evil.example', '/\t/evil.example', ' //evil.example', '\x00//evil.example', 'https:evil.example',
    'http:evil.example', 'HTTPS://EVIL.EXAMPLE', 'https://accounts.example.evil.example',
    'https://accounts.example@evil.example', 'http://accounts.example', 'javascript:alert(1)',
    'data:text/html,x', 'https://accounts.example/ok',
  ]
  const POLICIES = [
    ['default', compileRedirectPolicy(undefined).policy, new Set<string>()],
    ['allowExternal: [accounts]', compileRedirectPolicy({ allowExternal: ['https://accounts.example'] }).policy, new Set(['https://accounts.example'])],
    ['allowExternal: true', compileRedirectPolicy({ allowExternal: true }).policy, null],
  ] as const

  for (const [label, policy, allowed] of POLICIES) {
    let sent = 0
    let refused = 0
    for (const target of TARGETS) {
      let location: string | undefined
      try {
        location = redirectReply(target, undefined, policy).headers.get('location')
      } catch (error) {
        // Either refusal is a redirect that did not happen. The policy refuses
        // an origin; the header check refuses a NUL, CR or LF whatever the
        // policy allowed — which is how `allowExternal: true` still sends no
        // `Location: \0//evil.example`. The first run of this gate demanded
        // one code and flagged exactly that layering.
        const code = (error as { code?: string }).code
        if (code !== 'ZEN_REDIRECT_EXTERNAL' && code !== 'ZEN_HEADER_INVALID') {
          fail(`${label}: ${JSON.stringify(target)} threw ${String(code)}, not a refusal`)
        }
        refused++
        continue
      }
      sent++
      for (const base of BASES) {
        let url: URL
        try { url = new URL(location ?? '', base) } catch { fail(`${label}: sent ${JSON.stringify(target)}, which no browser can follow`); continue }
        const home = url.origin === new URL(base).origin
        const ok = home || (allowed === null ? url.protocol === 'http:' || url.protocol === 'https:' : allowed.has(url.origin))
        if (!ok) fail(`${label}: ${JSON.stringify(target)} reaches ${url.origin} on an ${base.slice(0, base.indexOf(':'))} page`)
      }
    }
    console.log(`    ${label.padEnd(28)} ${String(sent).padStart(2)} sent, ${String(refused).padStart(2)} refused — every one sent stays home or goes where it was allowed`)
    if (sent === 0 || refused === 0) fail(`${label}: the gate exercised only one side (${sent} sent, ${refused} refused)`)
  }
  console.log('')
}

// ── 3. a policy changes no generated byte ───────────────────────────────────

console.log('  3. A redirect policy changes no generated byte  (gate)\n')
{
  const build = (options: Record<string, unknown>): ZenApp => {
    const app = createApp({ router: new ZenRouter(), pathParser, logger: silent, dev: true, ...options }) as unknown as ZenApp
    app.get('/go', markSync((ctx: { redirect: (to: string) => unknown }) => ctx.redirect('/home')) as never)
    return app
  }
  const plain = build({})
  const allowing = build({ redirect: { allowExternal: ['https://accounts.example'] } })
  await plain.ready()
  await allowing.ready()
  const unit = (app: ZenApp, name: (n: string) => boolean): string => app.generatedSource().find((u) => name(u.name))?.source ?? ''
  const pipelines = [plain, allowing].map((app) => unit(app, (n) => n.startsWith('pipeline:')))
  const contexts = [plain, allowing].map((app) => unit(app, (n) => n === 'context'))
  const same = pipelines[0] === pipelines[1] && contexts[0] === contexts[1] && (pipelines[0] ?? '').length > 0
  console.log(`    no policy                     ${String(pipelines[0]?.length).padStart(5)} bytes of pipeline, ${String(contexts[0]?.length).padStart(5)} of context`)
  console.log(`    allowExternal: [one origin]   ${String(pipelines[1]?.length).padStart(5)} bytes of pipeline, ${String(contexts[1]?.length).padStart(5)} of context`)
  console.log(`    byte-identical: ${same ? 'yes — the policy is data on the shared ContextEnv, like config' : 'NO'}`)
  if (!same) fail('configuring redirect.allowExternal changed generated code (§9.4)')
  console.log('')
}

// ── 4. escapeHtml ───────────────────────────────────────────────────────────

console.log('  4. escapeHtml against the regex replace it replaced  (paired, median of 9)\n')
{
  const MAP: Readonly<Record<string, string>> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }
  const regex = (s: string): string => s.replace(/[&<>"']/g, (c) => MAP[c] ?? c)
  const INPUTS: Array<[string, string, number]> = [
    ['clean, 12 chars', 'Ada Lovelace', 2_000_000],
    ['dirty, 16 chars', 'Tom & "Jerry" <3', 1_000_000],
    ['clean, 1 KB', 'lorem ipsum dolor sit amet '.repeat(40), 200_000],
    ['dirty, 1 KB', 'lorem <ipsum> & "dolor" sit '.repeat(37), 50_000],
  ]
  for (const [label, input, iterations] of INPUTS) {
    if (escapeHtml(input) !== regex(input)) fail(`escapeHtml and the regex disagree on ${label}`)
    const r = paired(() => regex(input), () => escapeHtml(input), iterations)
    console.log(`    ${label.padEnd(18)} regex ${r.a.toFixed(1).padStart(7)} ns   escapeHtml ${r.b.toFixed(1).padStart(7)} ns   ${(1 / r.ratio).toFixed(1)}× ${r.ratio < 1 ? 'faster' : 'slower'}`)
  }
  console.log('')
  console.log('    The first version was the per-character scan alone, and it lost the clean-text rows by 30×:')
  console.log('    a charCodeAt loop over a clean kilobyte is ~2 µs, and irregexp finds "no markup" in ~70 ns.')
  console.log('    Most text is clean, so the regex search goes first and the scan starts where it stops.\n')
}

// ── 5. the tag ──────────────────────────────────────────────────────────────

console.log('  5. html`` against the same card written by hand  (paired, median of 9)\n')
{
  const user = { name: 'Ada <Lovelace>', bio: 'Analyst & "poet"', url: 'https://ada.example/about', site: 'ada.example', role: 'admin', posts: 42 }
  const card = (u: typeof user): SafeHtml =>
    html`<article class="card"><h2>${u.name}</h2><p>${u.bio}</p><a href="${u.url}">${u.site}</a><span title="${u.role}">${u.posts}</span></article>`
  const byHand = (u: typeof user): string =>
    '<article class="card"><h2>' + escapeHtml(u.name) + '</h2><p>' + escapeHtml(u.bio) + '</p><a href="' +
    escapeHtml(u.url) + '">' + escapeHtml(u.site) + '</a><span title="' + escapeHtml(u.role) + '">' +
    String(u.posts) + '</span></article>'
  if (String(card(user)) !== byHand(user)) fail('the tag and the hand-written card disagree')

  const r = paired(() => byHand(user), () => card(user), 500_000)
  console.log(`    by hand, escapeHtml per hole   ${r.a.toFixed(0).padStart(5)} ns`)
  console.log(`    html\`\`, six holes, one href    ${r.b.toFixed(0).padStart(5)} ns   ${r.ratio.toFixed(2)}× — the cached plan, the href check, one object`)
  console.log('    …and the hand-written one writes `javascript:` into the href, which is the difference being paid for.')

  // A fresh template object each call: what the first render of a call site costs.
  const parts = ['<article class="card"><h2>', '</h2><p>', '</p><a href="', '">', '</a><span title="', '">', '</span></article>']
  const first = nsPerCall(() => {
    const strings = Object.freeze(Object.assign([...parts], { raw: Object.freeze([...parts]) })) as unknown as TemplateStringsArray
    return html(strings, user.name, user.bio, user.url, user.site, user.role, user.posts)
  }, 50_000)
  console.log(`    first render of a template     ${first.toFixed(0).padStart(5)} ns   — its analysis, once per call site`)
  console.log('')
}

// ── 6. ctx.redirect ─────────────────────────────────────────────────────────

console.log('  6. ctx.redirect()  (paired against the unchecked builder, median of 9)\n')
{
  const { policy } = compileRedirectPolicy({ allowExternal: ['https://accounts.example'] })
  const EMPTY = Object.freeze({ kind: 'empty' as const })
  const unchecked = (to: string): unknown => {
    const reply = new MutableReply<null>(302, EMPTY)
    reply.headers.set('location', to)
    return reply
  }
  const rows: Array<[string, string]> = [
    ['a path — decided in two characters', '/dashboard'],
    ['an allowlisted origin — parsed', 'https://accounts.example/o/oauth2/auth?client_id=1&scope=openid'],
  ]
  for (const [label, target] of rows) {
    const r = paired(() => unchecked(target), () => redirectReply(target, undefined, policy), 500_000)
    console.log(`    ${label.padEnd(38)} ${r.a.toFixed(0).padStart(5)} ns → ${r.b.toFixed(0).padStart(5)} ns   +${(r.b - r.a).toFixed(0)} ns  ${noise(r.ratio, r.spread)}`)
  }
  const refusal = nsPerCall(() => {
    try { return redirectReply('https://evil.example/x', undefined, policy) } catch (error) { return error }
  }, 50_000)
  console.log(`    ${'a refusal — a ZenError with its stack'.padEnd(38)} ${refusal.toFixed(0).padStart(13)} ns   the 500 an attacker's ?next= buys`)
  console.log('')
}

// ── 7. what every JSON handler pays ─────────────────────────────────────────

console.log('  7. What a handler returning an object pays for `() => html``…```  (paired, median of 9)\n')
{
  // Three replicas of `finalize`'s shape, identical but for where the SafeHtml
  // check sits — the arms must do the same work, or the difference is the
  // arms (HANDOFF §8). The first run of this section compared a local replica
  // against the real cross-module `finalize` and reported +23 ns that was
  // mostly that difference.
  const shape = (check: 'none' | 'every object' | 'iterables only') => (value: unknown): unknown => {
    if (isReply(value)) return value
    if (value === undefined || value === null) return emptyReply(204)
    if (typeof value === 'string') return textReply(value)
    if (value instanceof Uint8Array) return bytesReply(value)
    if (typeof value === 'object' && value !== null && Symbol.asyncIterator in value) {
      if (check === 'iterables only' && isSafeHtml(value)) return value
      return value
    }
    if (check === 'every object' && isSafeHtml(value)) return value
    return jsonReply(value)
  }
  // Seven shapes in rotation: a real application's handlers return many, and a
  // check that is cheap at one call-site shape is not the same check at seven.
  const rows: object[] = [
    { id: 1, name: 'a' }, { a: 1 }, { x: 1, y: 2, z: 3 }, [1, 2], { items: [], total: 0 }, { id: 2, email: 'e' }, { ok: true },
  ]
  let n = 0
  const next = (): object => rows[n++ % rows.length] as object
  const none = shape('none')
  const everyObject = shape('every object')
  const iterablesOnly = shape('iterables only')
  const a = paired(() => none(next()), () => everyObject(next()), 2_000_000)
  const b = paired(() => none(next()), () => iterablesOnly(next()), 2_000_000)
  console.log(`    the check on every returned object     ${((a.ratio - 1) * 100).toFixed(1).padStart(5)}%  ${noise(a.ratio, a.spread)}   — the first design`)
  console.log(`    the check inside the iterable branch   ${((b.ratio - 1) * 100).toFixed(1).padStart(5)}%  ${noise(b.ratio, b.spread)}   — what ships`)
  console.log('    A fragment is an async iterable of its own markup, so `finalize` meets it in the branch it')
  console.log('    already takes for streams and ctx.sse() — and a JSON handler never reaches the check.')

  // And the real function, both ways, for the absolute numbers.
  const page = html`<h1>${'Hi'}</h1>`
  if (!isReply(finalize(page)) || !isReply(finalize(rows[0]))) fail('finalize did not produce a reply')
  console.log(`    finalize(object)                     ${nsPerCall(() => finalize(next()), 2_000_000).toFixed(0).padStart(5)} ns`)
  console.log(`    finalize(html\`…\`)                   ${nsPerCall(() => finalize(page), 2_000_000).toFixed(0).padStart(5)} ns\n`)
}

if (failures > 0) {
  console.log(`  ${failures} gate failure${failures === 1 ? '' : 's'}\n`)
  process.exitCode = 1
} else {
  console.log('  all gates passed\n')
}
