/**
 * What `url()` costs, and two gates — rfcs/0001 §5.7, I9.
 *
 * `node benchmarks/url/run.ts`
 *
 * `app.url(name, params, query)` builds the path of a named route and promises
 * that the route answers it, with those values. Two of the sections below fail
 * the build:
 *
 *   1. **A link never reaches another route.** A table built out of shadowing
 *      traps — a static route beside a parameter, a typed parameter beside an
 *      untyped one, a wildcard under a static prefix — crossed with values
 *      chosen to break a hand-built path: separators, dot segments, a lone
 *      surrogate, and the values that collide with the trap routes. Every URL
 *      `url()` returns is put through the WHATWG URL parser, which is what a
 *      browser does to an `href`, and the result is sent to the app; it must
 *      arrive at the route it was built for, with the values it was built from.
 *      Everything else must be refused. **Gated** — the shortcut a later
 *      optimisation reaches for is skipping the router check, and the unsafe
 *      version is the faster one, which is why §11.4's, §19.5's and §32.3's
 *      equivalents live in benchmarks too.
 *   2. **Naming and linking a route changes no generated byte.** The table is
 *      data built at boot and read when `url()` is called; it is not on the
 *      request path. **Gated.**
 *   3. **What a call costs**, by route shape, against the same path built by
 *      hand — with and without the `encodeURIComponent` a hand-built path
 *      needs and usually lacks.
 *   4. **What the router check costs**: one `match`, the price of the promise
 *      that a link reaches its own route.
 *   5. **What the table costs at boot**, for 500 named routes.
 */
import {
  createApp, isLocalUrl, markSync, UrlTable, type Logger, type RouteRecord, type ZenApp,
} from '@erenthedeveloper0/zen-core'
import { ZenRouter, parsePath } from '@erenthedeveloper0/zen-router'

const pathParser = {
  parse: (path: string) => {
    const parsed = parsePath(path)
    return { path: parsed.path, segments: parsed.segments }
  },
}

const silent: Logger = (() => {
  const noop = () => {}
  const logger = { level: 'fatal' as const, child: () => logger, trace: noop, debug: noop, info: noop, warn: noop, error: noop, fatal: noop }
  return logger
})()

const REPS = 9

let failures = 0
function fail(message: string): void {
  failures++
  console.log(`    ✖ ${message}`)
}

function nsPerCall(fn: () => unknown, iterations: number): number {
  let sink = 0
  for (let i = 0; i < Math.min(iterations, 50_000); i++) sink ^= fn() === undefined ? 0 : 1
  const samples: number[] = []
  for (let rep = 0; rep < REPS; rep++) {
    const start = process.hrtime.bigint()
    for (let i = 0; i < iterations; i++) sink ^= fn() === undefined ? 0 : 1
    samples.push(Number(process.hrtime.bigint() - start) / iterations)
  }
  if (sink === 42) console.log('')
  samples.sort((a, b) => a - b)
  return samples[Math.floor(samples.length / 2)] as number
}

/** Both arms inside every repetition, alternating which runs first (§9.9). */
function paired(a: () => unknown, b: () => unknown, iterations: number): { a: number; b: number; ratio: number } {
  let sink = 0
  for (let i = 0; i < 50_000; i++) sink ^= (a() === undefined ? 0 : 1) ^ (b() === undefined ? 0 : 2)
  const aTimes: number[] = []
  const bTimes: number[] = []
  const ratios: number[] = []
  for (let rep = 0; rep < REPS; rep++) {
    const order = rep % 2 === 0 ? [a, b] : [b, a]
    const times: number[] = []
    for (const arm of order) {
      const start = process.hrtime.bigint()
      for (let i = 0; i < iterations; i++) sink ^= arm() === undefined ? 0 : 1
      times.push(Number(process.hrtime.bigint() - start) / iterations)
    }
    const [first, second] = times as [number, number]
    const ta = rep % 2 === 0 ? first : second
    const tb = rep % 2 === 0 ? second : first
    aTimes.push(ta)
    bTimes.push(tb)
    ratios.push(tb / ta)
  }
  if (sink === 42) console.log('')
  ratios.sort((x, y) => x - y)
  return { a: Math.min(...aTimes), b: Math.min(...bTimes), ratio: ratios[Math.floor(ratios.length / 2)] as number }
}

const echo = markSync((ctx: { route: { name?: string } | null; params: unknown }) =>
  ({ route: ctx.route?.name ?? null, params: ctx.params }))

console.log('\n  URL generation — rfcs/0001 §5.7')
console.log(`  node ${process.version}\n`)

// ── 1. a link never reaches another route ───────────────────────────────────

console.log('  1. A link never reaches another route  (gate)\n')
{
  const TABLE: ReadonlyArray<readonly [name: string, path: string, param: string | null, kind: 'plain' | 'int' | 'wildcard' | null]> = [
    ['users.me', '/users/me', null, null],
    ['users.show', '/users/:id', 'id', 'plain'],
    ['items.byId', '/items/:id<int>', 'id', 'int'],
    ['items.byKey', '/items/:key', 'key', 'plain'],
    ['files.special', '/files/special', null, null],
    ['files', '/files/*path', 'path', 'wildcard'],
    ['page', '/:slug', 'slug', 'plain'],
  ]
  const VALUES: readonly unknown[] = [
    'me', 'special', 'users', '42', 42, -1, '4.2', 'chair', 'a/b', '../admin', '..', '.', '', 'a?b', 'a#b', '%2F',
    '%2e%2e', '\\evil.example', '//evil.example', 'https://evil.example', 'é', '日本 語', 'a\u0000b', 'x\uD800',
    'special/inner', 'docs/../../etc/passwd', ['a', 'b'], ['a/b'], {}, Number.NaN, 9007199254740993n, true,
  ]

  const app = createApp({ router: new ZenRouter(), pathParser, logger: silent }) as unknown as ZenApp
  for (const [name, path] of TABLE) app.get(path, { name }, echo as never)
  await app.ready()

  let built = 0
  let refused = 0
  for (const [name, , param, kind] of TABLE) {
    for (const value of param === null ? [undefined] : VALUES) {
      let url: string
      try {
        url = app.url(name, param === null ? {} : { [param]: value as never })
      } catch (error) {
        if ((error as { code?: string }).code !== 'ZEN_PARAM_MISMATCH') fail(`${name} ${String(value)}: ${String(error)}`)
        refused++
        continue
      }
      const browser = new URL(url, 'https://app.test/deep/page')
      if (browser.origin !== 'https://app.test' || !isLocalUrl(url)) fail(`${name}: ${url} leaves the origin`)
      if (browser.pathname !== url) fail(`${name}: a browser would request ${browser.pathname}, not ${url}`)
      const response = await app.inject('GET', browser.pathname)
      const got = response.status === 200 ? response.json<{ route: string; params: Record<string, unknown> }>() : null
      if (got === null || got.route !== name) {
        fail(`${name} ${JSON.stringify(value)}: ${url} reached ${got?.route ?? response.status}`)
        continue
      }
      const expected = param === null ? {}
        : { [param]: kind === 'int' ? Number(value) : Array.isArray(value) ? value.join('/') : String(value) }
      if (JSON.stringify(got.params) !== JSON.stringify(expected)) {
        fail(`${name} ${JSON.stringify(value)}: ${url} arrived as ${JSON.stringify(got.params)}`)
      }
      built++
    }
  }
  console.log(`    ${TABLE.length} routes × ${VALUES.length} values: ${built} links built, every one reached its route with its value`)
  console.log(`    ${refused} refused — a dot segment, an empty value, a type, a route that outranks this one`)
  if (built < 40 || refused < 40) fail(`the gate exercised too little: ${built} built, ${refused} refused`)
  console.log('')
}

// ── 2. naming and linking a route changes no generated byte ─────────────────

console.log('  2. Naming and linking a route changes no generated byte  (gate)\n')
{
  const build = async (named: boolean): Promise<ZenApp> => {
    const app = createApp({ router: new ZenRouter(), pathParser, logger: silent, dev: true }) as unknown as ZenApp
    app.get('/notes/:id<int>', named ? { name: 'notes.show' } : {}, echo as never)
    app.get('/notes', named ? { name: 'notes.list' } : {}, echo as never)
    await app.ready()
    if (named) app.url('notes.show', { id: 7 }, { from: 'feed' })
    return app
  }
  const [plain, linked] = [await build(false), await build(true)]
  const units = (app: ZenApp): string => app.generatedSource().map((u) => `${u.name}\n${u.source}`).join('\n')
  const same = units(plain) === units(linked) && units(plain).length > 0
  console.log(`    unnamed routes               ${String(units(plain).length).padStart(6)} bytes generated`)
  console.log(`    named, and url() called      ${String(units(linked).length).padStart(6)} bytes generated`)
  console.log(`    byte-identical: ${same ? 'yes — the table is data read by url(), never by a request' : 'NO'}`)
  if (!same) fail('naming or linking a route changed generated code (§9.4)')
  console.log('')
}

// ── 3. what a call costs ────────────────────────────────────────────────────

console.log('  3. What a call costs, against the same path built by hand\n')
{
  const app = createApp({ router: new ZenRouter(), pathParser, logger: silent }) as unknown as ZenApp
  app.get('/health', { name: 'health' }, echo as never)
  app.get('/users/:id<int>', { name: 'users.show' }, echo as never)
  app.get('/users/:id<int>/posts/:slug', { name: 'users.post' }, echo as never)
  app.get('/files/*path', { name: 'files' }, echo as never)
  for (let i = 0; i < 40; i++) app.get(`/r${i}/:id`, { name: `r${i}` }, echo as never)
  await app.ready()

  // Inputs fixed outside every timed loop (§8): building a template literal in
  // the loop is measuring string construction, not the thing named.
  const id = 42
  const slug = 'a title with spaces/and a slash'
  const pieces = ['docs', 'guide', 'intro.md']
  const query = { page: 2, tag: ['x', 'y'], q: 'a b' }

  const rows: Array<[string, () => unknown, () => unknown]> = [
    ['a static route', () => app.url('health'), () => '/health'],
    ['one <int> parameter', () => app.url('users.show', { id }), () => `/users/${id}`],
    ['two, one needing escapes', () => app.url('users.post', { id, slug }), () => `/users/${id}/posts/${encodeURIComponent(slug)}`],
    ['a wildcard, three pieces', () => app.url('files', { path: pieces }), () => `/files/${pieces.map(encodeURIComponent).join('/')}`],
    ['one parameter and a query', () => app.url('users.show', { id }, query),
      () => `/users/${id}?page=${query.page}&tag=${query.tag[0]}&tag=${query.tag[1]}&q=${encodeURIComponent(query.q)}`],
  ]
  for (const [label, url, byHand] of rows) {
    if (url() !== byHand()) fail(`${label}: url() gave ${String(url())}, by hand ${String(byHand())}`)
    const r = paired(byHand, url, 400_000)
    console.log(`    ${label.padEnd(28)} by hand ${r.a.toFixed(0).padStart(4)} ns   url() ${r.b.toFixed(0).padStart(5)} ns   (${r.ratio.toFixed(1)}×)`)
  }
  console.log('    By hand is the cheapest string there is, and it checks nothing — `/users/${id}` with an id of')
  console.log('    `../admin` is a different path. url() pays for the encoding, the type test and one router match.')
  console.log('')

  // ── 4. the router check ─────────────────────────────────────────────────
  //
  // The same paths url() builds above, matched by an identical router, so the
  // share is a subtraction of like from like (§8: only compare arms doing the
  // same shape of work).
  console.log('  4. What the router check costs — the share of a call that is the guarantee\n')
  const router = new ZenRouter().build(app.graph().routes as readonly RouteRecord[], { paramTypes: app.graph().paramTypes })
  const shapes: Array<[string, string, () => unknown]> = [
    ['a static route', app.url('health'), () => app.url('health')],
    ['one <int> parameter', app.url('users.show', { id }), () => app.url('users.show', { id })],
    ['two, one needing escapes', app.url('users.post', { id, slug }), () => app.url('users.post', { id, slug })],
  ]
  for (const [label, path, url] of shapes) {
    const r = paired(() => router.match('GET', path), url, 400_000)
    console.log(`    ${label.padEnd(28)} router.match ${r.a.toFixed(0).padStart(4)} ns of url()'s ${r.b.toFixed(0).padStart(5)} ns   (${((r.a / r.b) * 100).toFixed(0)}%)`)
  }
  console.log('    The same match the request will make, and the larger part of every call that has a parameter.')
  console.log('    It is what tells `/users/me` (a static route) from `/users/:id` given "me", and nothing cheaper')
  console.log('    can: the router is the authority on ranking. A boot-time analysis could skip it for a route')
  console.log('    nothing can outrank — and an analysis that is wrong is the bug url() exists to prevent.')
  console.log('')
}

// ── 5. what the table costs at boot ─────────────────────────────────────────

console.log('  5. What the table costs at boot\n')
{
  const app = createApp({ router: new ZenRouter(), pathParser, logger: silent }) as unknown as ZenApp
  for (let i = 0; i < 500; i++) app.get(`/r${i}/:id<int>/items/:slug`, { name: `r${i}` }, echo as never)
  await app.ready()
  const records = app.graph().routes as readonly RouteRecord[]
  const router = new ZenRouter().build(records, { paramTypes: app.graph().paramTypes })
  const perBuild = nsPerCall(() => new UrlTable(records, { router, maxQueryParams: 100 }), 200)
  console.log(`    500 named routes                    ${(perBuild / 1e6).toFixed(2)} ms, once — ${(perBuild / 500 / 1000).toFixed(2)} µs a route`)
  console.log('')
}

if (failures > 0) {
  console.log(`  ${failures} gate failure${failures === 1 ? '' : 's'}\n`)
  process.exitCode = 1
} else {
  console.log('  all gates passed\n')
}
